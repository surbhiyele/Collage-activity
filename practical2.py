a = 10
b = 5

# Arithmetic Operators
print("Addition:", a + b)
print("Division:", a / b)

# Relational Operators
print("a > b:", a > b)

# Logical Operators
print("a > 5 and b < 10:", a > 5 and b < 10)

# Bitwise Operators
print("a & b:", a & b)

# Assignment Operators
a += b
print("Updated a:", a)

# Membership Operators
list1 = [1, 2, 3, 4]
print("2 in list1:", 2 in list1)

# Identity Operators
x = 10
y = 10
print("x is y:", x is y)
